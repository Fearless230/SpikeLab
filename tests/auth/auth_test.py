from playwright.sync_api import sync_playwright
"""Sign-in and Squad connection scenarios, against a scripted stand-in for Supabase (tests/auth/fake-supabase.js):
not signed in, token expired after sleep, token refused mid-session, no signal, an unexpected sign-out, and logging out.
usage: python3 -m http.server 8765 (repo root), then python3 tests/auth/auth_test.py   (CHROME=/path/to/chrome)"""
import os
FAKE=open(os.path.join(os.path.dirname(os.path.abspath(__file__)),"fake-supabase.js")).read()
def step(t): print("\n#", t)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ.get("CHROME"),args=["--disable-3d-apis"])
    ctx=b.new_context(service_workers="block",viewport={"width":1280,"height":900})
    ctx.route("**/js/vendor/supabase-2.119.2.js",lambda r:r.fulfill(body=FAKE,content_type="text/javascript"))
    pg=ctx.new_page(); errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    sq=lambda: pg.inner_text("#squadRoot")[:110].replace("\n"," | ") if pg.locator("#squadRoot").count() else "(no squad)"
    pg.goto("http://127.0.0.1:8765/"); pg.wait_for_timeout(1500)
    step("1. Not signed in: continue without an account, open Squad, press Log in")
    pg.locator(".auth [data-skip]").click(); pg.wait_for_timeout(300)
    pg.fill("#p-name","Maya"); pg.fill("#p-age","16"); pg.fill("#p-height-cm","170"); pg.fill("#p-weight","60")
    pg.click("#wizNext"); pg.select_option("#p-pos","outside"); pg.select_option("#p-exp",index=2); pg.click("#wizNext"); pg.click("#wizNext")
    pg.evaluate("""(()=>{const g=document.querySelector('input[name="goal"]');g.checked=true;g.dispatchEvent(new Event('change',{bubbles:true}));})()""")
    pg.click("#wizSave"); pg.wait_for_timeout(600); pg.evaluate("location.hash='#squad'"); pg.wait_for_timeout(800)
    print("squad:", sq())
    pg.click('#squadRoot [data-auth="in"]'); pg.wait_for_timeout(300)
    print("login box visible:", pg.evaluate("!!document.querySelector('.auth:not([hidden])')"))
    pg.fill(".auth input[name=email]","maya@example.com"); pg.fill(".auth input[name=pw]","secret123")
    with pg.expect_navigation(): pg.click(".auth .go")
    pg.wait_for_timeout(1500); pg.evaluate("location.hash='#squad'"); pg.wait_for_timeout(1200)
    print("after log in -> squad:", sq())
    print("training data kept:", pg.evaluate("!!(VB.state&&VB.state.profile&&VB.state.profile.name)"))
    step("2. Token expired while the device slept, then the app is opened again")
    pg.evaluate("""(()=>{const s=JSON.parse(localStorage.getItem('fake-sess'));s.expires_at=Math.floor(Date.now()/1000)-600;localStorage.setItem('fake-sess',JSON.stringify(s));localStorage.setItem('fake-tokenok','0');})()""")
    pg.reload(); pg.wait_for_timeout(1500); pg.evaluate("location.hash='#squad'"); pg.wait_for_timeout(1500)
    print("squad:", sq(), "| token renewals:", pg.evaluate("__refreshes"), "| login box:", pg.evaluate("!!document.querySelector('.auth:not([hidden])')"))
    step("3. Token refused mid-session (expiry not yet due locally): a background refresh happens")
    pg.evaluate("__tokenOk=false"); pg.evaluate("document.dispatchEvent(new Event('visibilitychange'))"); pg.wait_for_timeout(1500)
    print("squad:", sq(), "| token renewals:", pg.evaluate("__refreshes"))
    step("4. No signal for a while")
    pg.evaluate("__netDown=true"); 
    for i in range(3): pg.evaluate("document.dispatchEvent(new Event('visibilitychange'))"); pg.wait_for_timeout(700)
    print("squad:", sq())
    pg.evaluate("__netDown=false"); pg.evaluate("document.dispatchEvent(new Event('visibilitychange'))"); pg.wait_for_timeout(1200)
    print("back online -> squad:", sq())
    step("5. The session ends without the player choosing to log out")
    pg.evaluate("__emit('SIGNED_OUT',null)"); pg.wait_for_timeout(600)
    print("login box:", pg.evaluate("(document.querySelector('.auth:not([hidden]) .msg')||{}).textContent"))
    print("training data kept:", pg.evaluate("!!localStorage.getItem('vb-journey-v2')||Object.keys(localStorage).some(k=>/vb|journey/.test(k))"))
    pg.fill(".auth input[name=email]","maya@example.com"); pg.fill(".auth input[name=pw]","secret123")
    with pg.expect_navigation(): pg.click(".auth .go")
    pg.wait_for_timeout(1500); pg.evaluate("location.hash='#squad'"); pg.wait_for_timeout(1200)
    print("after logging back in -> squad:", sq())
    step("6. Log out on purpose")
    pg.evaluate("location.hash='#profile'"); pg.wait_for_timeout(600)
    with pg.expect_navigation(): pg.click("#acctBar [data-out]")
    pg.wait_for_timeout(1200)
    print("login box:", pg.evaluate("!!document.querySelector('.auth:not([hidden])')"), "| device cleared:", pg.evaluate("!localStorage.getItem('fake-sess')"))
    print("\npage errors:", errs)
    b.close()
